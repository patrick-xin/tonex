'use client'

import {
  buildContrastBundle,
  type ExportOptions,
  exportCss,
  exportDart,
  exportDesignMd,
  exportJson,
  exportNativeCss,
  type Mode,
  selectSeedHex,
} from '@tonex/core'
import { selectHydrated, selectPortable, useSource } from '@tonex/core-react'
import { useMemo } from 'react'
import { useShallow } from 'zustand/react/shallow'
import { type ExportTab, resolveExportRoute } from './resolve-export-route'

// why: the per-tab routing decision (which exporter, extension, header policy)
// lives in resolveExportRoute — one exhaustively-typed table instead of six
// scattered return sites. ExportTab is owned there and re-exported here so the
// existing import sites keep resolving.
export type { ExportTab } from './resolve-export-route'

// why: header is the export's provenance trail. seed + variant always carry
// signal; date is what users actually find useful when comparing two pasted
// exports in a project. contrast is per-mode (#123) and the only field with a
// baseline value (0 = no adjustment, MCU default); emitting `contrast: 0`
// reads as applied where none is. Omit when both modes are baseline; otherwise
// emit a single value when light === dark and `light/dark` when they diverge,
// so re-importers can recover non-default contrast unchanged. Source state
// clamps each mode to [0, 1] (issue #33) so the equality check is exact.
export function formatHeader(
  seed: string,
  variant: string,
  contrast: { light: number; dark: number },
  date: string,
): string {
  const parts = [`source: ${seed}`, `variant: ${variant}`]
  if (contrast.light !== 0 || contrast.dark !== 0) {
    const value =
      contrast.light === contrast.dark ? `${contrast.light}` : `${contrast.light}/${contrast.dark}`
    parts.push(`contrast: ${value}`)
  }
  parts.push(`date: ${date}`)
  return ['/*', ' * Generated by tonex', ` * ${parts.join(' · ')}`, ' */', '', ''].join('\n')
}

export interface ExportContent {
  exportContent: string
  ext: string
}

export function useExportContent({
  exportTab,
  mode,
  options,
}: {
  exportTab: ExportTab
  // why: DESIGN.md has no light/dark axis (unlike the CSS tabs, which co-emit
  // both), so the dialog picks one mode and threads it here. Ignored by every
  // other tab. See export-button.tsx's ExportModeChooser.
  mode: Mode
  options: ExportOptions
}): ExportContent {
  const hydrated = useSource(selectHydrated)
  // why: useShallow + selectPortable mirrors useResolvedTokens — one stable
  // PortableTheme reference per source change. buildContrastBundle routes
  // through the unified derive cache (issue #20), keyed on (source,
  // contrastLevel), so toggling format-only flags doesn't re-derive the
  // (potentially 3×) tier set and the default tier shares its slot with
  // useResolvedTokens / applyDom.
  const portable = useSource(useShallow(selectPortable))
  const seedHex = useSource(selectSeedHex)
  const variant = useSource((s) => s.variant)
  const contrastLevel = useSource((s) => s.contrastLevel)

  return useMemo(() => {
    if (!hydrated) return { exportContent: '/* Loading… */', ext: 'css' }

    // why: ADR-0021 commitment 5 — buildContrastBundle is lazy and shared by the
    // JSON and CSS paths, so it's built once below the hydration guard. Toggling
    // includeContrastVariants triggers the 3× derive only on dialog mount /
    // option change, not on every source render. WYSIWYG-visibility per
    // commitment 7 — the string we hand to the dialog pane equals what the user
    // pastes byte-for-byte.
    const bundle = buildContrastBundle(portable, options)
    const route = resolveExportRoute(exportTab)

    // why: each exporter takes a different shape (Design.md needs the chosen
    // mode; JSON also needs the portable source; the css tabs need a layer), so
    // the route's discriminant picks the call — but the routing *decision*
    // (which exporter, ext, header) is the single table above, not this switch.
    // Design.md is @google/design.md interop (bare `colors:` YAML, sRGB hex so
    // colorFormat is ignored); JSON reshapes the same DerivedTheme into MTB JSON
    // (ADR-0029); Dart into a Flutter MaterialTheme (ADR-0021 c.9); CSS is
    // framework-agnostic light-dark() pairs; Tailwind/shadcn are the md/shadcn
    // layers (shadcn omits @import/@theme since the user already owns them).
    const body = (() => {
      switch (route.exporter) {
        case 'designMd':
          return exportDesignMd(bundle, mode, options)
        case 'json':
          return exportJson(portable, bundle, options)
        case 'dart':
          return exportDart(bundle, options)
        case 'nativeCss':
          return exportNativeCss(bundle, options)
        case 'css':
          return exportCss(bundle, route.layer, options)
      }
    })()

    // why: data formats (JSON/Dart/Design.md) stay header-free — a /* */ banner
    // breaks a JSON parse or a `colors:` paste. Only the css family gets the
    // provenance header. Date is ISO yyyy-mm-dd (sortable, locale-free) captured
    // at recompute so the banner reflects when this export was generated.
    if (!route.header) return { exportContent: body, ext: route.ext }
    const date = new Date().toISOString().slice(0, 10)
    return {
      exportContent: formatHeader(seedHex, variant, contrastLevel, date) + body,
      ext: route.ext,
    }
  }, [exportTab, mode, hydrated, portable, options, seedHex, variant, contrastLevel])
}
